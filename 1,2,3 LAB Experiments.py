from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

print("Libraries imported successfully!")

vectorizer = TfidfVectorizer(
    stop_words="english"
)

document_vectors = vectorizer.fit_transform(documents)

print("Documents indexed successfully!")
print("Index shape:", document_vectors.shape)

def retrieve_documents(question, top_k=3):

    # Convert question into a vector
    question_vector = vectorizer.transform([question])

    # Calculate similarity
    similarities = cosine_similarity(
        question_vector,
        document_vectors
    )[0]

    # Get highest similarity indexes
    top_indices = similarities.argsort()[::-1][:top_k]

    results = []

    for index in top_indices:
        results.append({
            "document": documents[index],
            "score": similarities[index]
        })

    return results

question = "What does ESP32 provide for IoT projects?"

results = retrieve_documents(question)

for i, result in enumerate(results):

    print("=" * 60)
    print("Document:", i + 1)
    print("Similarity Score:", round(result["score"], 4))
    print(result["document"])

def create_context(question, top_k=3):

    results = retrieve_documents(question, top_k)

    context = ""

    for i, result in enumerate(results):

        context += f"""
Document {i + 1}:

{result["document"]}

"""

    return context

question = "What does ESP32 provide for IoT projects?"

context = create_context(question)

print(context)

def rag_answer(question):

    # Step 1: Retrieve relevant documents
    context = create_context(question)

    # Step 2: Create prompt
    prompt = f"""
Answer the question using only the information in the documents.

Documents:
{context}

Question:
{question}

Answer:
"""

    # Step 3: Tokenize
    inputs = tokenizer(
        prompt,
        return_tensors="pt",
        truncation=True
    )

    # Step 4: Generate answer
    outputs = model.generate(
        **inputs,
        max_new_tokens=100
    )

    # Step 5: Decode
    answer = tokenizer.decode(
        outputs[0],
        skip_special_tokens=True
    )

    return answer

question = "What does ESP32 provide for IoT projects?"

answer = rag_answer(question)

print("Question:")
print(question)

print("\nAnswer:")
print(answer)

